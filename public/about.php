              <h1>About Integrity Watch EU </h1>
              <p>Integrity Watch EU is a hub that allows everyone to monitor the integrity of the EU’s decision makers. We collect data on the activities of EU officials and members of the European Parliament (MEPs), and make it easily accessible for all. This allows you to monitor EU decision-making for potential conflicts of interest and undue influence. Brussels is home to nearly 13,000 lobby organisations. That’s over 18 organisations for every MEP. With so much lobbying activity, it’s crucial that everyone can see who’s meeting whom, and why.</p>

              <h2>Where does the data come from?</h2>
              <p>Our platform currently contains four sections:</p>
              <h3>Commission meetings</h3>
              <p>Lobby meetings held with the European Commission, combining meeting records of senior and managerial staff with information from the EU Transparency Register, the register of lobbyists in Brussels. Updated daily.</p>
              <p>Self-reported lobby meeting data of senior and management-level European Commission officials contains a range of insights on current dynamics and content of lobby activities. Additionally, data from the <a href="https://transparency-register.europa.eu/index_en" target="_blank">Transparency Register</a> provides key information on lobbyists, including employees, interests represented and the topics they’re active on. This data is retrieved from the <a href="https://data.europa.eu/data/datasets/european-commission-meetings-with-interest-representatives?locale=en" target="_blank">EU Open Data portal</a>.</p>
              <h3>EU Lobbyists</h3>
              <p>Key information on EU lobbyists, declared on the EU Transparency Register. Updated daily.</p>
              <p>Registered lobby organisations engaging in EU-related influencing activities must disclose information regarding their identity, interests represented, financial spending and income, as well as any organisations they are connected to (i.e.: memberships of larger networks or their own members). This data is retrieved from the <a href="https://data.europa.eu/data/datasets/transparency-register?locale=en" target="_blank">EU Open Data Portal</a>.</p>
              <h3>MEP incomes</h3>
              <p>Side activities performed and side income earned by Members of the European Parliament. Updated every month.</p>
              <p>MEPs must declare the side activities they perform in declaration forms on the European Parliament’s website. Our database collates these entries, allowing anyone to browse what MEPs are doing outside of their mandate, and how much they are paid for it. This data is retrieved from the <a href="https://www.europarl.europa.eu/meps/en/full-list" target="_blank">MEPs’ individual pages</a> on the European Parliament’s website.</p>
              <h3>MEP meetings</h3>
              <p>Lobby meetings held with MEPs and their assistants. Updated daily.</p>
              <p>MEPs and their assistants must disclose all lobby meetings falling under the scope of the Transparency Register. However, this dataset is not combined with the EU Transparency Register due to a lack of integration from the European Parliament’s side. MEPs are allowed to meet unregistered lobbyists, which also must be published. This data is retrieved from the <a href="https://www.europarl.europa.eu/meps/en/full-list" target="_blank">MEPs’ individual pages</a>, on the European Parliament’s website.</p>

              <h2>What about data re-use?</h2>
              <p>Integrity Watch EU data is exclusively retrieved from the European institution’s official websites. This data is entirely self-reported. TI EU & Integrity Watch EU bears no responsibility for the accuracy of the original data. Where further processing is required, this is indicated in each section of the tool, with additional details on the exact treatments performed on the source data.</p>
              <p>Please report inaccurate or incomplete information including a link to the source.</p>
              <p>If you are using our data for research, journalism or other purposes, please always confirm your findings with the original information on the EU Institutions’ websites, and please credit us:</p>
              <p><i>Integrity Watch EU by Transparency International EU</i></p>
              <p>Integrity Watch EU was first launched by TI EU in October 2014. The platform has since seen multiple iterations, with new functionalities and datasets added. It is our principal data-driven tool to foster greater understanding of EU decision-making and push for higher standards against conflicts of interest and undue influence. Check TI EU’s <a href="https://transparency.eu/" target="_blank">main website</a> for our latest research and key recommendations.</p>
              <p>IW EU is part of a larger ecosystem of IW platforms, currently deployed in 17 European countries, with six more planned in 2025. National IW versions and corresponding datasets can be accessed via the <a href="https://data.integritywatch.eu/" target="_blank">IW datahub</a>.</p>

